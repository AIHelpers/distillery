"""Vision-language (document AI) training task module (plan 06).

Scope note (mirrors the plan's step-by-step task 3, "vision.py for one model
family (Qwen-VL)"): the heavy training path targets the Qwen2-VL family
specifically (AutoProcessor + Qwen2VLForConditionalGeneration), the
recommended-default, QLoRA-friendly model from the catalog. PaliGemma and
Florence-2 are catalogued (internal/infra/simulation/model_selector.go) as
alternatives to evaluate/add trainer support for later, per the plan's own
"verify licenses and support before finalizing" note.

The Go contract is the same one every other task module follows: JSONL
progress in job-dir/progress.jsonl, a final metrics.json, and the trained
adapter written under output_dir. Dataset records are
{"image": "<blob key>", "prompt": "...", "answer": "...", "doc_id": "...",
"page": N} — "image" resolves to a file under `images_dir` (the blob store's
per-task directory), not raw bytes, keeping the JSONL small.
"""

from __future__ import annotations

import json
import re
import signal
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Optional

from trainer.progress import ProgressWriter

DEFAULT_TARGET_MODS = ["q_proj", "k_proj", "v_proj", "o_proj"]

# Register with the task registry at import time (idempotent).
from trainer.tasks import register  # noqa: E402  (import after module).


@dataclass
class Config:
    job_id: str
    base_model: str
    dataset_path: str
    output_dir: str
    images_dir: str = ""
    epochs: int = 3
    batch_size: int = 1
    gradient_accumulation_steps: int = 8
    learning_rate: float = 1e-4
    warmup_steps: int = 20
    max_image_side: int = 1280
    max_new_tokens: int = 256
    freeze_vision_encoder: bool = True
    lora_rank: int = 16
    lora_alpha: int = 32
    lora_dropout: float = 0.05
    lora_target_mods: list[str] = field(default_factory=lambda: list(DEFAULT_TARGET_MODS))
    load_4bit: bool = True
    grad_checkpoint: bool = True
    validation_split: float = 0.15
    max_validation_samples: int = 30
    model_cache_dir: Optional[str] = None
    resume_from: Optional[str] = None
    seed: int = 42
    # The task's JSON Schema (when the extraction output is structured), used
    # to compute a schema-valid JSON rate rather than a bare JSON-parses rate.
    json_schema: Optional[str] = None

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "Config":
        known = {f.name: f for f in cls.__dataclass_fields__.values()}  # type: ignore[attr-defined]
        kwargs: dict[str, Any] = {}
        for k, v in d.items():
            if k in known:
                kwargs[k] = v
        return cls(**kwargs)


def load_config(path: Path) -> Config:
    with open(path, "r", encoding="utf-8") as f:
        raw = json.load(f)
    cfg = Config.from_dict(raw)
    cfg.dataset_path = str(Path(raw.get("dataset_path", cfg.dataset_path)))
    cfg.output_dir = str(Path(raw.get("output_dir", cfg.output_dir)))
    return cfg


# --- Dataset ---.


def read_vision_records(path: Path) -> list[dict[str, Any]]:
    """Reads dataset.jsonl, skipping lines that aren't a usable vision
    example (missing image key or prompt). Mirrors read_preference_records'
    "skip the bad ones, keep the rest" contract."""
    records: list[dict[str, Any]] = []

    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue

            try:
                obj = json.loads(line)
            except ValueError:
                continue

            image = str(obj.get("image", "")).strip()
            prompt = str(obj.get("prompt", "")).strip()

            if not image or not prompt:
                continue

            records.append(
                {
                    "image": image,
                    "prompt": prompt,
                    "answer": str(obj.get("answer", "")),
                    "doc_id": obj.get("doc_id", ""),
                    "page": obj.get("page", 0),
                }
            )

    return records


def resolve_image_path(images_dir: str, image_key: str) -> Path:
    """Resolves a dataset record's blob key to a file path under
    images_dir. filepath traversal is neutralized by taking only the
    basename -- image keys are opaque IDs generated by the blob store, never
    user-supplied paths."""
    return Path(images_dir) / Path(image_key).name


def load_pil_image(images_dir: str, image_key: str, max_side: int):
    """Loads and (if needed) downsamples one training image. Imports PIL
    lazily so importing this module for its pure functions (tests, the CLI's
    --help) doesn't require Pillow to be installed."""
    from PIL import Image

    path = resolve_image_path(images_dir, image_key)
    img = Image.open(path).convert("RGB")

    if max_side > 0 and max(img.size) > max_side:
        scale = max_side / max(img.size)
        new_size = (max(1, int(img.width * scale)), max(1, int(img.height * scale)))
        img = img.resize(new_size, Image.LANCZOS)

    return img


# --- Field-level evaluation (invoice/receipt-style extraction) ---.


def try_parse_json(text: str) -> Optional[dict[str, Any]]:
    """Best-effort JSON object parse: strips a ```json ... ``` fence some
    models wrap structured output in, then attempts a strict parse."""
    text = text.strip()

    fence = re.match(r"^```(?:json)?\s*(.*?)\s*```$", text, re.DOTALL)
    if fence:
        text = fence.group(1).strip()

    try:
        parsed = json.loads(text)
    except (TypeError, ValueError):
        return None

    return parsed if isinstance(parsed, dict) else None


_NORMALIZE_STRIP_RE = re.compile(r"[,$%\s]")


def normalize_field_value(value: Any) -> str:
    """Normalizes a field value for comparison: numbers/dates/amounts vary in
    formatting (",", "$", trailing whitespace) far more than in substance, so
    exact-match on the raw string would understate real quality (plan 06,
    section 9: "exact match and F1 ... with normalization for amounts/dates")."""
    s = str(value).strip().lower()
    return _NORMALIZE_STRIP_RE.sub("", s)


def _token_f1(pred: str, gold: str) -> float:
    """SQuAD-style token-overlap F1 between two normalized strings."""
    pred_toks = list(pred)
    gold_toks = list(gold)

    if not pred_toks and not gold_toks:
        return 1.0

    if not pred_toks or not gold_toks:
        return 0.0

    common: dict[str, int] = {}
    for c in pred_toks:
        common[c] = common.get(c, 0) + 1

    overlap = 0
    for c in gold_toks:
        if common.get(c, 0) > 0:
            overlap += 1
            common[c] -= 1

    if overlap == 0:
        return 0.0

    precision = overlap / len(pred_toks)
    recall = overlap / len(gold_toks)

    return round(2 * precision * recall / (precision + recall), 4)


def field_level_metrics(
    predictions: list[Optional[dict[str, Any]]],
    golds: list[dict[str, Any]],
) -> dict[str, dict[str, float]]:
    """Computes per-field exact-match/F1/support over parsed JSON
    predictions vs. gold answers. A prediction of None (failed to parse, or
    the field is simply absent) counts as a miss for every gold field."""
    fields: dict[str, list[tuple[float, float]]] = {}

    for pred, gold in zip(predictions, golds):
        for key, gold_val in gold.items():
            gold_norm = normalize_field_value(gold_val)
            pred_val = pred.get(key) if isinstance(pred, dict) else None
            pred_norm = normalize_field_value(pred_val) if pred_val is not None else ""

            exact = 1.0 if pred_norm == gold_norm else 0.0
            f1 = _token_f1(pred_norm, gold_norm)

            fields.setdefault(key, []).append((exact, f1))

    out: dict[str, dict[str, float]] = {}

    for key, pairs in fields.items():
        n = len(pairs)
        out[key] = {
            "exact_match": round(sum(p[0] for p in pairs) / n, 4),
            "f1": round(sum(p[1] for p in pairs) / n, 4),
            "support": n,
        }

    return out


def macro_field_f1(field_metrics: dict[str, dict[str, float]]) -> float:
    if not field_metrics:
        return 0.0

    return round(sum(m["f1"] for m in field_metrics.values()) / len(field_metrics), 4)


def document_accuracy(predictions: list[Optional[dict[str, Any]]], golds: list[dict[str, Any]]) -> float:
    """Fraction of examples where every gold field matched exactly (plan's
    "document-level accuracy (all fields correct)")."""
    if not golds:
        return 0.0

    correct = 0

    for pred, gold in zip(predictions, golds):
        if not isinstance(pred, dict):
            continue

        if all(normalize_field_value(pred.get(k)) == normalize_field_value(v) for k, v in gold.items()):
            correct += 1

    return round(correct / len(golds), 4)


def _levenshtein(a: str, b: str) -> int:
    if a == b:
        return 0

    if not a:
        return len(b)

    if not b:
        return len(a)

    prev = list(range(len(b) + 1))

    for i, ca in enumerate(a, start=1):
        cur = [i] + [0] * len(b)

        for j, cb in enumerate(b, start=1):
            cost = 0 if ca == cb else 1
            cur[j] = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + cost)

        prev = cur

    return prev[-1]


def anls_score(pred: str, gold: str) -> float:
    """Normalized Levenshtein Similarity for one (pred, gold) pair, the
    standard document-VQA metric for free-text answers. Scores below 0.5 are
    clamped to 0 per the ANLS convention (a "wrong enough" answer shouldn't
    get partial credit just for sharing characters)."""
    pred, gold = pred.strip().lower(), gold.strip().lower()

    if not gold:
        return 1.0 if not pred else 0.0

    dist = _levenshtein(pred, gold)
    nls = 1 - dist / max(len(pred), len(gold), 1)

    return round(nls, 4) if nls >= 0.5 else 0.0


def average_anls(predictions: list[str], golds: list[str]) -> float:
    if not golds:
        return 0.0

    scores = [anls_score(p, g) for p, g in zip(predictions, golds)]

    return round(sum(scores) / len(scores), 4)


def json_validity_rate(predictions: list[str], schema_str: Optional[str]) -> float:
    """Fraction of predictions that parse as JSON, and — when a schema is
    given — also satisfy it."""
    if not predictions:
        return 0.0

    validator = None

    if schema_str:
        try:
            import jsonschema  # type: ignore

            validator = jsonschema.Draft7Validator(json.loads(schema_str))
        except Exception:  # noqa: BLE001 - fall back to parse-only below.
            validator = None

    valid = 0

    for text in predictions:
        parsed = try_parse_json(text)
        if parsed is None:
            continue

        if validator is not None and not validator.is_valid(parsed):
            continue

        valid += 1

    return round(valid / len(predictions), 4)


def evaluate_predictions(
    predicted_texts: list[str],
    gold_answers: list[str],
    schema_str: Optional[str],
) -> dict[str, Any]:
    """Runs the full plan-9 metric suite over a held-out split's generations.
    Field metrics are computed only when every gold answer parses as JSON
    (the invoice/receipt/form extraction case); otherwise the free-text ANLS
    path is used."""
    gold_parsed = [try_parse_json(g) for g in gold_answers]
    is_structured = bool(gold_answers) and all(g is not None for g in gold_parsed)

    metrics: dict[str, Any] = {
        "json_valid_rate": json_validity_rate(predicted_texts, schema_str),
    }

    if is_structured:
        pred_parsed = [try_parse_json(t) for t in predicted_texts]
        fm = field_level_metrics(pred_parsed, gold_parsed)  # type: ignore[arg-type]
        metrics["field_metrics"] = fm
        metrics["macro_field_f1"] = macro_field_f1(fm)
        metrics["document_accuracy"] = document_accuracy(pred_parsed, gold_parsed)  # type: ignore[arg-type]
    else:
        metrics["anls"] = average_anls(predicted_texts, gold_answers)

    return metrics


