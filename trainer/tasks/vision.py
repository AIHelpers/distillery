class DistilleryProgressCallback:
    """Emits one JSON progress line per on_log event (mirrors sft.py's)."""

    def __init__(self, writer: ProgressWriter, total_steps: int):
        self.writer = writer
        self.total_steps = total_steps

    def on_log(self, args, state, control, logs=None):  # noqa: ARG002
        loss = logs.get("loss") if logs else None
        eval_loss = logs.get("eval_loss") if logs else None
        lr = logs.get("learning_rate") if logs else None
        self.writer.progress(
            step=state.global_step,
            total_steps=self.total_steps,
            epoch=state.epoch,
            loss=loss,
            eval_loss=eval_loss,
            lr=lr,
        )


def save_metrics(output_dir: Path, metrics: dict[str, Any]) -> None:
    metrics_path = output_dir / "metrics.json"
    with open(metrics_path, "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2, ensure_ascii=False)
    print(f"metrics written to {metrics_path}", file=sys.stderr)


def _build_collate_fn(processor, max_image_side: int, images_dir: str):
    """Builds the multimodal collate function: renders each record's chat
    turns through the processor's chat template, tokenizes prompt+answer
    together, and masks the prompt (+ padding) tokens out of the loss so
    only the answer contributes to the gradient -- the same "mask
    non-answer tokens" contract sft.py's tokenizer path follows for plain
    text."""
    import torch

    def _messages(prompt: str, answer: Optional[str]):
        user_turn = {"role": "user", "content": [{"type": "image"}, {"type": "text", "text": prompt}]}
        if answer is None:
            return [user_turn]
        return [user_turn, {"role": "assistant", "content": [{"type": "text", "text": answer}]}]

    def collate(batch: list[dict[str, Any]]):
        images = [load_pil_image(images_dir, r["image"], max_image_side) for r in batch]

        prompt_texts = [
            processor.apply_chat_template(_messages(r["prompt"], None), tokenize=False, add_generation_prompt=True)
            for r in batch
        ]
        full_texts = [
            processor.apply_chat_template(_messages(r["prompt"], r["answer"]), tokenize=False, add_generation_prompt=False)
            for r in batch
        ]

        prompt_enc = processor(text=prompt_texts, images=images, padding=True, truncation=True, return_tensors="pt")
        full_enc = processor(text=full_texts, images=images, padding=True, truncation=True, return_tensors="pt")

        labels = full_enc["input_ids"].clone()
        pad_id = processor.tokenizer.pad_token_id

        for i in range(labels.size(0)):
            prompt_len = int(prompt_enc["attention_mask"][i].sum().item())
            labels[i, :prompt_len] = -100

        labels[full_enc["input_ids"] == pad_id] = -100

        full_enc["labels"] = labels

        return full_enc

    return collate


def run(cfg: Config, writer: ProgressWriter, job_dir: Path, dataset_path: str) -> int:
    """Runs the vision-language QLoRA fine-tune and returns the process exit code."""
    stop_requested = False

    def handle_sigterm(signum, frame):  # noqa: ARG001
        nonlocal stop_requested
        stop_requested = True
        writer.event("signal", signal="SIGTERM", msg="graceful stop requested")

    signal.signal(signal.SIGTERM, handle_sigterm)

    if not cfg.images_dir:
        writer.event("error", message="images_dir is required for vision_lm training")
        save_metrics(job_dir, {"status": "failed", "error": "images_dir is required"})
        return 1

    # --- Import heavy libs lazily so --help / config errors are cheap. ---
    import torch
    from transformers import AutoProcessor, BitsAndBytesConfig, Qwen2VLForConditionalGeneration, TrainingArguments
    from peft import LoraConfig, get_peft_model, prepare_model_for_kbit_training

    device_map = "auto"
    if torch.cuda.is_available():
        writer.event("device", device_type="cuda", name=torch.cuda.get_device_name(0))
    else:
        writer.event("device", device_type="cpu")
        device_map = "cpu"

    try:
        processor = AutoProcessor.from_pretrained(cfg.base_model, cache_dir=cfg.model_cache_dir, trust_remote_code=True)

        model_kwargs: dict[str, Any] = {
            "cache_dir": cfg.model_cache_dir,
            "device_map": device_map,
            "trust_remote_code": True,
        }

        if cfg.load_4bit and torch.cuda.is_available():
            model_kwargs["quantization_config"] = BitsAndBytesConfig(
                load_in_4bit=True,
                bnb_4bit_quant_type="nf4",
                bnb_4bit_compute_dtype=torch.float16,
                bnb_4bit_use_double_quant=True,
            )

        model = Qwen2VLForConditionalGeneration.from_pretrained(cfg.base_model, **model_kwargs)

        # Freeze the vision tower by default (plan: "freeze the vision
        # encoder by default") -- LoRA trains only the language tower
        # (+ optionally the projector), which is what keeps VRAM in reach of
        # a single consumer GPU for a 2B-7B VLM.
        if cfg.freeze_vision_encoder and hasattr(model, "visual"):
            for p in model.visual.parameters():
                p.requires_grad_(False)

        if cfg.load_4bit and torch.cuda.is_available():
            model = prepare_model_for_kbit_training(model, use_gradient_checkpointing=cfg.grad_checkpoint)

        lora_config = LoraConfig(
            r=cfg.lora_rank,
            lora_alpha=cfg.lora_alpha,
            lora_dropout=cfg.lora_dropout,
            target_modules=cfg.lora_target_mods or DEFAULT_TARGET_MODS,
            task_type="CAUSAL_LM",
        )
        model = get_peft_model(model, lora_config)
        model.print_trainable_parameters()

        records = read_vision_records(Path(dataset_path))
        if not records:
            raise ValueError("Dataset is empty or has no readable vision records")

        if cfg.validation_split > 0 and len(records) >= 5:
            cut = max(1, int(len(records) * (1 - cfg.validation_split)))
            train_records, eval_records = records[:cut], records[cut:]
        else:
            train_records, eval_records = records, []

        collate_fn = _build_collate_fn(processor, cfg.max_image_side, cfg.images_dir)

        class _ListDataset(torch.utils.data.Dataset):
            def __init__(self, items: list[dict[str, Any]]):
                self.items = items

            def __len__(self) -> int:
                return len(self.items)

            def __getitem__(self, idx: int) -> dict[str, Any]:
                return self.items[idx]

        train_ds = _ListDataset(train_records)

        output_dir = Path(cfg.output_dir)
        checkpoint_dir = output_dir / "checkpoints"
        checkpoint_dir.mkdir(parents=True, exist_ok=True)

        training_args = TrainingArguments(
            output_dir=str(checkpoint_dir),
            num_train_epochs=cfg.epochs,
            per_device_train_batch_size=cfg.batch_size,
            gradient_accumulation_steps=cfg.gradient_accumulation_steps,
            learning_rate=cfg.learning_rate,
            warmup_steps=cfg.warmup_steps,
            logging_steps=1,
            save_strategy="epoch",
            save_total_limit=2,
            report_to=[],
            seed=cfg.seed,
            fp16=torch.cuda.is_available(),
            gradient_checkpointing=cfg.grad_checkpoint,
            remove_unused_columns=False,
        )

        total_steps = max(1, len(train_ds) // (cfg.batch_size * cfg.gradient_accumulation_steps)) * cfg.epochs
        callback = DistilleryProgressCallback(writer, total_steps)

        from transformers import Trainer

        trainer = Trainer(
            model=model,
            args=training_args,
            train_dataset=train_ds,
            data_collator=collate_fn,
            callbacks=[callback],
        )

        writer.event("status", value="starting_training", total_steps=total_steps)

        trainer.train(resume_from_checkpoint=cfg.resume_from)

        adapter_path = output_dir / "adapter"
        model.save_pretrained(str(adapter_path))
        processor.save_pretrained(str(output_dir / "processor"))

        final_metrics: dict[str, Any] = {"status": "completed", "kind": "vision_lm", "train_examples": len(train_records)}

        # Held-out generation + the plan-9 metric suite (field F1, ANLS, JSON
        # validity, document accuracy), bounded by max_validation_samples the
        # same way sft.py bounds its JSON-validity generation pass.
        if eval_records:
            sample = eval_records[: cfg.max_validation_samples]
            gold_answers = [r["answer"] for r in sample]

            predicted_texts = _generate_predictions(model, processor, sample, cfg)
            final_metrics.update(evaluate_predictions(predicted_texts, gold_answers, cfg.json_schema))

            # Zero-shot baseline: the plan's definition of done is "beats a
            # zero-shot baseline on field F1", so re-run generation with the
            # LoRA adapter disabled -- the base VLM, prompted the same way,
            # at no extra load cost since it's the same model object already
            # in memory. This differs from classifier.py's majority-class
            # "sanity floor" baseline, which stands in for a real zero-shot
            # pass that isn't cheaply available there; here a true zero-shot
            # comparison IS cheap (peft's disable_adapter), so we use it.
            if hasattr(model, "disable_adapter"):
                with model.disable_adapter():
                    baseline_texts = _generate_predictions(model, processor, sample, cfg)
                baseline_metrics = evaluate_predictions(baseline_texts, gold_answers, cfg.json_schema)
                baseline_field_f1 = baseline_metrics.get("macro_field_f1")
                if baseline_field_f1 is not None and "macro_field_f1" in final_metrics:
                    final_metrics["baseline_field_f1"] = baseline_field_f1
                    final_metrics["delta_field_f1"] = round(final_metrics["macro_field_f1"] - baseline_field_f1, 4)

            writer.event("eval", **{k: v for k, v in final_metrics.items() if k not in ("status", "kind")})

        writer.event("complete", status="completed", kind="vision_lm")
        save_metrics(job_dir, final_metrics)

        if stop_requested:
            writer.event("status", value="stopped_by_user")
            return 130

        return 0

    except Exception as exc:  # noqa: BLE001
        writer.event("error", message=str(exc), class_name=type(exc).__name__)
        save_metrics(job_dir, {"status": "failed", "error": str(exc)})
        print(f"FATAL: {exc}", file=sys.stderr)
        return 1
    finally:
        writer.close()


def _generate_predictions(model, processor, records: list[dict[str, Any]], cfg: Config) -> list[str]:
    """Greedy-generates the model's answer for each held-out record."""
    import torch

    model.eval()
    outputs: list[str] = []

    with torch.no_grad():
        for r in records:
            image = load_pil_image(cfg.images_dir, r["image"], cfg.max_image_side)
            messages = [{"role": "user", "content": [{"type": "image"}, {"type": "text", "text": r["prompt"]}]}]
            text = processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)

            inputs = processor(text=[text], images=[image], return_tensors="pt")
            inputs = {k: v.to(model.device) for k, v in inputs.items()}

            generated = model.generate(**inputs, max_new_tokens=cfg.max_new_tokens, do_sample=False)
            new_tokens = generated[:, inputs["input_ids"].shape[1] :]
            outputs.append(processor.batch_decode(new_tokens, skip_special_tokens=True)[0].strip())

    return outputs


def _runner(cfg_dict: dict, writer: object, job_dir: str, dataset_path: str) -> int:
    c = cfg_dict if isinstance(cfg_dict, Config) else Config.from_dict(cfg_dict)
    c.dataset_path = dataset_path or c.dataset_path

    return run(c, writer, Path(job_dir), c.dataset_path)


register("vision_lm", _runner)
